import { AgentRunner, AgentRunContext, AgentRunResult, AgentError } from '../runtime/types.js';
import { AgentRole } from '../../models/enums.js';
import { generateId } from '../../../utils/ids.js';
import { getTimestamp } from '../../../utils/time.js';
import { AgentFeedEvent } from '../../events/event-types.js';

async function wait(ms: number, fast?: boolean, signal?: AbortSignal): Promise<void> {
  if (signal?.aborted) {
    throw new AgentError('Execution aborted by signal', false);
  }
  const delay = fast ? Math.max(10, Math.floor(ms / 15)) : ms;
  await new Promise<void>((resolve, reject) => {
    const timer = setTimeout(() => {
      cleanup();
      resolve();
    }, delay);
    const onAbort = () => {
      clearTimeout(timer);
      cleanup();
      reject(new AgentError('Execution aborted by signal', false));
    };
    const cleanup = () => {
      signal?.removeEventListener('abort', onAbort);
    };
    signal?.addEventListener('abort', onAbort);
  });
}

export class MockPlannerAgent implements AgentRunner {
  readonly role: AgentRole = 'planner';

  async run(context: AgentRunContext): Promise<AgentRunResult> {
    const { taskId, nodeId, goal, node, inputArtifacts, signal, toolRegistry, eventBus, artifactService, fast, workspaceRoot } = context;
    const actorId = `agent_${this.role}`;
    const correlationId = generateId('corr');
    const messages: AgentFeedEvent[] = [];

    const publish = async <T = Record<string, unknown>>(
      type: AgentFeedEvent['type'],
      payload: T
    ): Promise<AgentFeedEvent<T>> => {
      const evt = await eventBus.publish<T>({
        eventId: generateId('evt'),
        taskId,
        nodeId,
        type,
        timestamp: getTimestamp(),
        actorType: 'agent',
        actorId,
        correlationId,
        payload,
      });
      messages.push(evt as unknown as AgentFeedEvent);
      return evt;
    };

    try {
      await publish('node_started', {
        nodeId,
        title: node.title,
        assignedAgentRole: this.role,
      });

      await wait(150, fast, signal);

      await publish('agent_message', {
        nodeId,
        kind: 'thought',
        content: `Synthesizing repository discovery brief and formulating concrete implementation plan for "${goal}"...`,
      });

      await wait(150, fast, signal);

      // Locate repository brief artifact
      const briefArtifact = inputArtifacts?.find(
        (a) => a.title.toLowerCase().includes('brief') || a.path.includes('brief')
      );

      const toolContext = {
        taskId,
        nodeId,
        actorId,
        correlationId,
        artifactService,
        eventBus,
        workspaceRoot,
      };

      let briefContent = '';
      if (briefArtifact) {
        try {
          const res = await toolRegistry.execute('read_artifact', { artifactId: briefArtifact.id }, toolContext);
          if (res.ok && (res.data as { content?: string })?.content) {
            briefContent = (res.data as { content: string }).content;
          }
        } catch {
          // Fall back gracefully
        }
      }

      const planMarkdown = `# Implementation Plan: ${goal}

**Generated By**: Planner Specialist Agent
**Date**: ${getTimestamp()}
**Status**: Ready for Coder Execution

## Context & Objectives
- Target Goal: ${goal}
- Repository Awareness: Explorer brief analyzed.
${briefContent ? `\n### Upstream Explorer Findings\n${briefContent.slice(0, 400)}...\n` : ''}

## Architecture & File Strategy
1. **Target Modules**:
   - Create input validation module with strict runtime schemas.
   - Wire input checks into target endpoints/methods.
2. **Security Boundaries**:
   - Zero modifications to protected paths.
   - All files restricted to workspace boundary.
3. **Verification & Testing Strategy**:
   - Execute allowlisted test suite.
   - Ensure zero regressions.
`;

      const artRes = await toolRegistry.execute('create_markdown_artifact', {
        title: `Implementation Plan: ${node.title}`,
        filename: 'implementation-plan.md',
        content: planMarkdown,
      }, toolContext);

      const createdArtifact = artRes.data as { artifactId: string; path: string };

      await wait(100, fast, signal);

      await publish('node_completed', {
        nodeId,
        outputArtifactId: createdArtifact.artifactId,
        summary: `Implementation plan generated and recorded in ${createdArtifact.artifactId}`,
      });

      return {
        status: 'done',
        outputArtifactIds: [createdArtifact.artifactId],
        messages,
        usage: {
          inputTokens: 250,
          outputTokens: 380,
          estimatedCostUsd: 0.003,
        },
      };
    } catch (err) {
      const isAbort = signal?.aborted;
      const agentErr =
        err instanceof AgentError
          ? err
          : new AgentError(err instanceof Error ? err.message : String(err), !isAbort);

      if (!isAbort) {
        await publish('error_occurred', {
          nodeId,
          error: agentErr.message,
          fatal: false,
        });
      }

      return {
        status: isAbort ? 'blocked' : 'failed',
        outputArtifactIds: [],
        messages,
        usage: { inputTokens: 40, outputTokens: 20 },
        error: agentErr,
      };
    }
  }
}
